/* ── Downloads ───────────────────────────────────────────────────────────── */

/**
 * A file download that carries proof of ownership.
 *
 * `/api/exports` accepts a signed link or the search's owner, and a plain
 * anchor carries no Supabase token. So a click mints a short-lived signed link
 * (which also works when the file lives on a hosted engine) and follows it in a
 * detached anchor, so the page keeps its state.
 *
 * The link is served from the page's own origin. A route handler only sees the
 * deployment's internal address, so the minted URL can name a host the browser
 * cannot reach (0.0.0.0, or a private 10.x address behind a proxy); the
 * signature covers the search, file and expiry, so the path is portable.
 */
function safeDownloadUrl(minted: string | null, fallback: string): string {
  return minted ? sameOriginLink(minted) : fallback;
}

function followUrl(url: string) {
  const a = document.createElement('a');
  a.href = url;
  a.rel = 'noopener';
  document.body.appendChild(a);
  a.click();
  a.remove();
}

function DownloadButton({
  searchId,
  file,
}: {
  searchId: string;
  file: ExportFile;
}) {
  const [state, setState] = useState<'idle' | 'busy' | 'done' | 'error'>('idle');
  const fallback = `/api/exports/${encodeURIComponent(file.name)}?search_id=${encodeURIComponent(searchId)}`;

  const download = useCallback(async () => {
    setState('busy');
    try {
      const res = await fetch(
        `/api/search/${encodeURIComponent(searchId)}/export-link?file=${encodeURIComponent(file.name)}`,
        { headers: await authHeaders() }
      );
      const body = await res.json().catch(() => null);
      const minted = res.ok && typeof body?.url === 'string' ? body.url : null;
      if (!minted) {
        // The direct route also needs proof of ownership, so falling back to it
        // would 404 silently — and the button would still say "Started". Report
        // the failure instead of pretending a download began.
        setState('error');
        window.setTimeout(() => setState('idle'), 4000);
        return;
      }
      followUrl(safeDownloadUrl(minted, fallback));
      setState('done');
      window.setTimeout(() => setState('idle'), 2500);
    } catch {
      setState('error');
      window.setTimeout(() => setState('idle'), 4000);
    }
  }, [fallback, file.name, searchId]);

  return (
    <button
      type="button"
      onClick={download}
      disabled={state === 'busy'}
      title={
        state === 'error'
          ? 'The download link could not be created. Reload the page and try again.'
          : undefined
      }
      className="inline-flex shrink-0 items-center gap-1.5 rounded-md border border-line-strong bg-surface px-2.5 py-1.5 text-[11px] font-medium text-fg transition-colors hover:border-accent hover:text-accent disabled:opacity-55"
    >
      {state === 'busy' ? (
        <SpinnerIcon className="h-3 w-3 animate-spin-slow" />
      ) : state === 'done' ? (
        <CheckIcon className="h-3 w-3 text-success" />
      ) : state === 'error' ? (
        <AlertIcon className="h-3 w-3 text-danger" />
      ) : (
        <DownloadIcon className="h-3 w-3" />
      )}
      {state === 'busy'
        ? 'Preparing…'
        : state === 'done'
          ? 'Started'
          : state === 'error'
            ? 'Try again'
            : 'Download'}
    </button>
  );
}

/**
 * A signed URL that opens a file directly in Cytoscape desktop.
 *
 * Cytoscape's own fetcher sends no session cookie, so the plain download URL
 * cannot be used there. The API mints a capability URL that expires; this
 * copies it and names the one step Cytoscape needs.
 */
function CytoscapeLink({ searchId, filename }: { searchId: string; filename: string }) {
  const [state, setState] = useState<'idle' | 'busy' | 'copied' | 'error'>('idle');

  async function copyLink() {
    setState('busy');
    try {
      const res = await fetch(
        `/api/search/${encodeURIComponent(searchId)}/export-link?file=${encodeURIComponent(filename)}`,
        { headers: await authHeaders() }
      );
      const body = await res.json().catch(() => null);
      if (!res.ok || typeof body?.url !== 'string') throw new Error('no link');
      await navigator.clipboard.writeText(sameOriginLink(body.url));
      setState('copied');
      window.setTimeout(() => setState('idle'), 3500);
    } catch {
      setState('error');
    }
  }

  return (
    <button
      type="button"
      onClick={copyLink}
      disabled={state === 'busy'}
      title="Copy a signed URL for File → Import → Network from URL in Cytoscape"
      className="inline-flex shrink-0 items-center gap-1 rounded-md border border-line px-2 py-1 text-[11px] font-medium text-fg-muted transition-colors hover:border-accent hover:text-accent disabled:opacity-55"
    >
      {state === 'busy'
        ? 'Signing…'
        : state === 'copied'
          ? 'Link copied'
          : state === 'error'
            ? 'Link failed'
            : 'Cytoscape link'}
    </button>
  );
}

/* ── Cloud archive ───────────────────────────────────────────────────────── */

function CloudArchive({ search }: Props) {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const archive = search.storage;
  if (!archive) return null;

  async function openArchive() {
    setBusy(true);
    setError(null);
    try {
      const res = await fetch(
        `/api/search/${encodeURIComponent(search.search_id)}/cloud-link`,
        { headers: await authHeaders() }
      );
      const body = await res.json().catch(() => null);
      if (!res.ok || !body?.url) {
        throw new Error(
          (typeof body?.detail === 'string' && body.detail) ||
            body?.detail?.message ||
            'Could not create a download link.'
        );
      }
      followUrl(safeDownloadUrl(body.url, body.url));
    } catch (err: any) {
      setError(err?.message || 'Could not create a download link.');
    } finally {
      setBusy(false);
    }
  }

  return (
    <div className="rounded-lg border border-accent-line bg-accent-soft px-4 py-3">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="min-w-0">
          <p className="text-xs font-semibold text-fg">Archived in Google Cloud Storage</p>
          <p className="mt-0.5 text-[11px] text-fg-muted">
            {archive.filename} · {archive.size_display} · one archive per search, kept
            until you delete it
          </p>
        </div>
        <button
          type="button"
          onClick={openArchive}
          disabled={busy}
          className="shrink-0 rounded-md border border-accent bg-surface px-2.5 py-1.5 text-[11px] font-medium text-accent transition-colors hover:bg-accent-soft disabled:opacity-55"
        >
          {busy ? 'Preparing…' : 'Download archive'}
        </button>
      </div>
      {error && (
        <p className={cx(note('danger'), 'mt-2')} role="alert">
          {error}
        </p>
      )}
    </div>
  );
}

/* ── Overview ────────────────────────────────────────────────────────────── */

function PotencyBars({ compounds }: { compounds: DecisionIntel['feasibility']['compounds'] }) {
  if (compounds.length === 0) return null;
  const max = Math.max(...compounds.map((c) => c.potency_score), 10);
  return (
    <ul className="mt-2 space-y-1.5">
      {compounds.slice(0, 6).map((c) => (
        <li key={c.uid} className="grid grid-cols-[minmax(0,1fr)_auto] items-center gap-x-3 gap-y-1">
          <span className="truncate text-xs text-fg" title={c.name}>
            {c.name}
          </span>
          <span className="tabular-nums text-[11px] text-fg-muted">
            {c.potency_score.toFixed(2)}
          </span>
          <span className="col-span-2 flex items-center gap-1.5">
            <span aria-hidden className="h-1.5 flex-1 overflow-hidden rounded-full bg-surface-3">
              <span
                className={cx(
                  'block h-full rounded-full',
                  c.grade === 'A' || c.grade === 'B'
                    ? 'bg-success'
                    : c.grade === 'C' || c.grade === 'D'
                      ? 'bg-warning'
                      : 'bg-danger'
                )}
                style={{ width: `${Math.max(4, (c.potency_score / max) * 100)}%` }}
              />
            </span>
            <span className={cx('w-3 text-[10px] font-semibold', gradeTone(c.grade))}>
              {c.grade}
            </span>
            <span className="w-16 shrink-0 text-right text-[10px] text-fg-subtle">
              {c.datapoints} pt{c.datapoints === 1 ? '' : 's'}
            </span>
          </span>
        </li>
      ))}
    </ul>
  );
}

