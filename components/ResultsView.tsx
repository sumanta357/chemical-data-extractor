'use client';

import { AlertIcon, DownloadIcon } from '@/components/icons';
import { cx } from '@/components/ui';
import type { SearchState } from '@/lib/types';

interface Props {
  search: SearchState;
}

/** Plain-language description of what each export actually contains. */
const FILE_INFO: Record<string, { label: string; contains: string }> = {
  '.xlsx': {
    label: 'Excel workbook',
    contains: 'Every sheet of the graph — nodes, edges, bioactivity, summary',
  },
  '.csv': {
    label: 'CSV table',
    contains: 'One row per node or edge, ready for pandas, R or Excel',
  },
  '.graphml': {
    label: 'GraphML',
    contains: 'The whole graph for Gephi, Cytoscape or yEd',
  },
  '.cypher': {
    label: 'Cypher script',
    contains: 'CREATE statements for loading into Neo4j',
  },
  '.ttl': {
    label: 'Turtle (RDF)',
    contains: 'Triples for RDF stores such as Blazegraph or Jena',
  },
  '.json': {
    label: 'JSON',
    contains: 'Structured nodes, edges, metadata and vector index',
  },
  '.parquet': {
    label: 'Parquet',
    contains: 'Columnar node and edge tables for large-scale analysis',
  },
  '.png': {
    label: 'PNG image',
    contains: 'Rendered 2D structure of the compound',
  },
  '.md': {
    label: 'Markdown',
    contains: 'Human-readable summary of the search',
  },
  '.txt': {
    label: 'Text',
    contains: 'Plain-text rendering of the search result',
  },
};

function infoFor(name: string) {
  const ext = `.${name.split('.').pop()?.toLowerCase() ?? ''}`;
  return FILE_INFO[ext] ?? { label: 'File', contains: 'Generated by the search engine' };
}

export default function ResultsView({ search }: Props) {
  const { export_files: files } = search;

  return (
    <section className="panel overflow-hidden">
      <div className="flex flex-wrap items-baseline justify-between gap-x-3 gap-y-1 px-5 py-4">
        <h2 className="text-sm font-semibold text-fg">Export files</h2>
        <p className="text-xs text-fg-subtle tabular-nums">
          {files.length} {files.length === 1 ? 'file' : 'files'}
          {search.elapsed_seconds != null &&
            ` · finished in ${search.elapsed_seconds.toFixed(1)}s`}
        </p>
      </div>

      <ul className="border-t border-line">
        {files.map((file) => {
          const info = infoFor(file.name);
          return (
            <li key={file.name} className="border-b border-line last:border-b-0">
              <a
                href={`/api/exports/${file.name}?search_id=${search.search_id}`}
                target="_blank"
                rel="noopener noreferrer"
                className="group flex items-center gap-3 px-5 py-3 transition-colors hover:bg-surface-2"
              >
                <span
                  aria-hidden
                  className="w-[52px] shrink-0 rounded border border-line bg-surface-2 px-1 py-0.5 text-center font-mono text-[10px] font-medium uppercase text-fg-muted"
                >
                  {file.name.split('.').pop()?.slice(0, 5)}
                </span>
                <span className="min-w-0 flex-1">
                  <span className="block truncate text-sm text-fg group-hover:text-accent">
                    {file.name}
                  </span>
                  <span className="block truncate text-xs text-fg-subtle">
                    {info.label} · {info.contains} · {file.size_display}
                  </span>
                </span>
                <DownloadIcon className="h-4 w-4 shrink-0 text-fg-subtle group-hover:text-accent" />
                <span className="sr-only">Download {file.name}</span>
              </a>
            </li>
          );
        })}
      </ul>

      <p
        className={cx(
          'flex items-start gap-2 border-t border-line bg-surface-2 px-5 py-3',
          'text-xs leading-relaxed text-fg-muted'
        )}
      >
        <AlertIcon className="mt-px h-4 w-4 shrink-0 text-fg-subtle" />
        <span>
          Exports are temporary. The server deletes generated files about 30
          minutes after the search completes, so download anything you want to
          keep.
        </span>
      </p>
    </section>
  );
}
