function extension(name: string): string {
  return (name.split('.').pop() ?? '').toUpperCase().slice(0, 4);
}

/* ── Formatting ──────────────────────────────────────────────────────────── */

function compact(n: number | null | undefined): string {
  if (n == null || !Number.isFinite(n)) return '—';
  if (n >= 1_000_000) return `${(n / 1_000_000).toFixed(1)}M`;
  if (n >= 10_000) return `${Math.round(n / 1000)}k`;
  return n.toLocaleString();
}

function gradeTone(grade: string): string {
  if (grade === 'A' || grade === 'B') return 'text-success';
  if (grade === 'C' || grade === 'D') return 'text-warning';
  if (grade === 'F') return 'text-danger';
  return 'text-fg-muted';
}

function gradeBg(grade: string): string {
  if (grade === 'A' || grade === 'B') return 'bg-success-soft border-success-line';
  if (grade === 'C' || grade === 'D') return 'bg-warning-soft border-warning-line';
  if (grade === 'F') return 'bg-danger-soft border-danger-line';
  return 'bg-surface-2 border-line';
}

function ipTone(status: DecisionIntel['ip']['status']): string {
  if (status === 'green') return 'text-success';
  if (status === 'yellow') return 'text-warning';
  // No records is not a green light; it gets the neutral tone, never a
  // reassuring one.
  if (status === 'insufficient_data') return 'text-fg-subtle';
  return 'text-danger';
}

function ipLabel(status: DecisionIntel['ip']['status']): string {
  if (status === 'insufficient_data') return 'No data';
  return status.charAt(0).toUpperCase() + status.slice(1);
}

/** One line of a long PubChem statement, without cutting mid-word. */
function shorten(text: string, max = 220): string {
  const clean = (text || '').trim();
  if (clean.length <= max) return clean;
  const cut = clean.slice(0, max);
  const space = cut.lastIndexOf(' ');
  return `${(space > 60 ? cut.slice(0, space) : cut).trimEnd()}…`;
}

